        <h2>How to borrow</h2>
        <p>Follow these steps to get your equipment.</p>
    </div>
    <div class="sidebar-scroll">
        <div class="sidebar-body">
            <ol class="timeline">
                <li>
                    <strong>Log in</strong>
                    Enter your username and password, then the new code from your email.
                </li>
                <li>
                    <strong>Choose your equipment</strong>
                    Pick what you need and the date you will use it. The request is saved under your account.
                </li>
                <li>
                    <strong>Pick it up</strong>
                    Go to the laboratory and tell the staff your ID Number. They check your borrow record in the system and hand over the equipment.
                </li>
                <li>
                    <strong>Return it on time</strong>
                    Bring it back in good condition. The staff marks it as returned in the system.
                </li>
            </ol>
            <div class="side-help">
                <strong>Forgot your password?</strong>
                Use the Forgot Password link on the log-in page and answer your security question.
